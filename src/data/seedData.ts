// Generate realistic 30-day historical time-series for every source
function buildHistoryPoints(): PriceHistoryPoint[] {
  const points: PriceHistoryPoint[] = [];
  const baseDate = new Date('2026-11-13T05:00:00Z');
  const fxToUsd: Record<string, number> = {
    USD: 1,
    ILS: 0.273,
    EUR: 1.085,
    GBP: 1.275,
  };

  INITIAL_SOURCES.forEach((src, srcIdx) => {
    const baseUsd = src.currentRawPrice * fxToUsd[src.currency];
    const baseNetUsd = src.taxRules.sourceIncludesTax
      ? baseUsd / (1 + src.taxRules.sourceVatRate)
      : baseUsd;

    for (let day = 29; day >= 0; day--) {
      const dt = new Date(baseDate.getTime() - day * 86400_000);
      // Deterministic realistic price oscillation + occasional promo dips
      const wave = Math.sin((day + srcIdx * 3) * 0.45) * 0.032;
      const dip = (day === 12 || day === 13) && srcIdx % 2 === 0 ? -0.055 : 0;
      const factor = day === 0 ? 1 : 1 + wave + dip;

      const rawPrice = Number((src.currentRawPrice * factor).toFixed(2));
      const netPriceUsd = Number((baseNetUsd * factor).toFixed(2));
      const grossPriceUsd = Number((netPriceUsd * 1.18).toFixed(2));

      points.push({
        id: `hist_${src.id}_${day}`,
        sourceConfigId: src.id,
        productId: src.productId,
        scrapedAt: dt.toISOString(),
        rawPrice,
        currency: src.currency,
        netPriceUsd,
        grossPriceUsd,
        stockStatus: day === 0 ? src.currentStock : 'in_stock',
      });
    }
  });

  return points;
}

